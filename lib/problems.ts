import { ProblemSchema, type Difficulty, type Problem } from "./types";

import climbingStairs from "@/data/problems/climbing-stairs.json";
import containerWithMostWater from "@/data/problems/container-with-most-water.json";
import houseRobber from "@/data/problems/house-robber.json";
import longestSubstringNoRepeat from "@/data/problems/longest-substring-no-repeat.json";
import searchInsertPosition from "@/data/problems/search-insert-position.json";
import validPalindrome from "@/data/problems/valid-palindrome.json";

// Validate at load so a malformed JSON file fails loudly instead of mid-interview.
export const PROBLEMS: Problem[] = [
  validPalindrome,
  containerWithMostWater,
  longestSubstringNoRepeat,
  climbingStairs,
  houseRobber,
  searchInsertPosition,
].map((p) => ProblemSchema.parse(p));

function randomOf<T>(items: T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}

/**
 * Picks a problem for the topic and difficulty. Falls back to the same topic at
 * any difficulty, then to any problem, until the bank is filled out and custom
 * topics are generated by Gemini (milestone 6).
 */
export function pickProblem(topic: string, difficulty: Difficulty): Problem {
  const sameTopic = PROBLEMS.filter((p) => p.topic === topic);
  const exact = sameTopic.filter((p) => p.difficulty === difficulty);
  if (exact.length) return randomOf(exact);
  if (sameTopic.length) return randomOf(sameTopic);
  return randomOf(PROBLEMS);
}
